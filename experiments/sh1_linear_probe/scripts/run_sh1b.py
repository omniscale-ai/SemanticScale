#!/usr/bin/env python3
"""SH1b: Re-evaluate SH1 probes with document-level (grouped) splits.

Addresses data leakage concern: SH1 split spans randomly, allowing
spans from the same paper to appear in both train and test.
This script splits by paper_id instead, then re-runs the same probe
pipeline and compares results.

Usage:
    cd playground/SLoD-SH1
    python scripts/run_sh1b.py
"""

import json
import logging
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
from sklearn.metrics import f1_score
from sklearn.model_selection import GroupKFold, GroupShuffleSplit
from sklearn.preprocessing import StandardScaler

# Add project root to path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.train_probe import (
    run_hyperparameter_sweep,
    train_and_evaluate,
    _make_classifier,
)
from src.utils import LABEL_MAP, LABEL_NAMES, load_config, load_spans, setup_logging


def create_grouped_splits(
    spans: list[dict],
    ratios: list[float],
    seed: int,
    save_path: Path | None = None,
) -> dict:
    """Create train/val/test splits grouped by paper_id (no paper overlap)."""
    paper_ids = np.array([s["paper_id"] for s in spans])
    labels = np.array([LABEL_MAP[s["label"]] for s in spans])

    train_ratio, val_ratio, test_ratio = ratios

    # Stage 1: train vs (val+test) by paper
    gss1 = GroupShuffleSplit(
        n_splits=1, test_size=val_ratio + test_ratio, random_state=seed
    )
    train_idx, valtest_idx = next(
        gss1.split(np.arange(len(spans)), labels, groups=paper_ids)
    )

    # Stage 2: val vs test by paper (within held-out papers)
    valtest_papers = paper_ids[valtest_idx]
    relative_test = test_ratio / (val_ratio + test_ratio)
    gss2 = GroupShuffleSplit(n_splits=1, test_size=relative_test, random_state=seed)
    val_local, test_local = next(
        gss2.split(
            np.arange(len(valtest_idx)),
            labels[valtest_idx],
            groups=valtest_papers,
        )
    )
    val_idx = valtest_idx[val_local]
    test_idx = valtest_idx[test_local]

    # Verify zero paper overlap
    train_papers = set(paper_ids[train_idx])
    val_papers = set(paper_ids[val_idx])
    test_papers = set(paper_ids[test_idx])
    assert len(train_papers & test_papers) == 0, "Paper leak: train ∩ test"
    assert len(train_papers & val_papers) == 0, "Paper leak: train ∩ val"
    assert len(val_papers & test_papers) == 0, "Paper leak: val ∩ test"

    splits = {
        "train": sorted(train_idx.tolist()),
        "val": sorted(val_idx.tolist()),
        "test": sorted(test_idx.tolist()),
        "split_type": "grouped_by_paper",
        "n_papers_train": len(train_papers),
        "n_papers_val": len(val_papers),
        "n_papers_test": len(test_papers),
    }

    if save_path is not None:
        save_path = Path(save_path)
        save_path.parent.mkdir(parents=True, exist_ok=True)
        with open(save_path, "w") as f:
            json.dump(splits, f, indent=2)
        logging.info(f"Grouped splits saved to {save_path}")

    return splits


def label_distribution(labels: np.ndarray) -> dict[str, int]:
    """Return per-class counts."""
    counts = Counter(labels.tolist())
    return {LABEL_NAMES[k]: counts.get(k, 0) for k in range(len(LABEL_NAMES))}


def run_groupkfold_cv(
    embeddings: np.ndarray,
    labels: np.ndarray,
    paper_ids: np.ndarray,
    clf_config: dict,
    C: float,
    n_folds: int = 5,
) -> dict:
    """Run GroupKFold cross-validation, return mean ± std macro-F1."""
    gkf = GroupKFold(n_splits=n_folds)
    fold_f1s = []

    for fold_i, (train_idx, test_idx) in enumerate(
        gkf.split(embeddings, labels, groups=paper_ids)
    ):
        scaler = StandardScaler()
        X_train = scaler.fit_transform(embeddings[train_idx])
        X_test = scaler.transform(embeddings[test_idx])
        y_train = labels[train_idx]
        y_test = labels[test_idx]

        clf = _make_classifier(clf_config["type"], C, clf_config["params"])
        clf.fit(X_train, y_train)
        y_pred = clf.predict(X_test)
        f1 = float(f1_score(y_test, y_pred, average="macro"))
        fold_f1s.append(f1)
        logging.info(f"  Fold {fold_i + 1}/{n_folds}: macro-F1 = {f1:.4f}")

    return {
        "fold_f1s": fold_f1s,
        "mean_f1": float(np.mean(fold_f1s)),
        "std_f1": float(np.std(fold_f1s)),
        "n_folds": n_folds,
    }


def generate_report(
    grouped_results: dict,
    original_results: dict,
    split_stats: dict,
    cv_results: dict,
    report_path: Path,
) -> None:
    """Generate SH1b markdown report."""
    lines = []
    lines.append("# SH1b: Document-Level Split Validation")
    lines.append("")
    lines.append("> Generated by `run_sh1b.py`")
    lines.append("")
    lines.append("## Motivation")
    lines.append("")
    lines.append(
        "SH1 split spans randomly across train/val/test with label stratification "
        "only. Spans from the same paper could appear in both train and test, "
        "allowing the probe to exploit paper-level features (topic, style, vocabulary) "
        "rather than learning pure SLoD signal. This experiment re-runs the same "
        "pipeline with document-level (paper_id) grouping to quantify the inflation."
    )
    lines.append("")

    # Split statistics
    lines.append("## Split Statistics")
    lines.append("")
    for split_name in ["train", "val", "test"]:
        s = split_stats[split_name]
        dist = ", ".join(f"{k}={v}" for k, v in s["label_dist"].items())
        lines.append(
            f"- **{split_name}**: {s['n_papers']} papers, {s['n_spans']} spans ({dist})"
        )
    lines.append(f"- **Zero paper overlap confirmed**: ✓")
    lines.append("")

    # Results comparison
    lines.append("## Results Comparison")
    lines.append("")
    lines.append("| Model + Clf | SH1 (random) | SH1b (grouped) | Delta | Inflation % |")
    lines.append("|---|---|---|---|---|")

    best_grouped_f1 = 0.0
    for model_key in grouped_results:
        if model_key in ("baselines", "best_config", "confound_check", "binary_fallback"):
            continue
        for clf_key in grouped_results[model_key]:
            g_f1 = grouped_results[model_key][clf_key]["test"]["macro_f1"]
            o_f1 = original_results.get(model_key, {}).get(clf_key, {}).get("test", {}).get("macro_f1", 0)
            delta = o_f1 - g_f1
            pct = (delta / g_f1 * 100) if g_f1 > 0 else 0
            lines.append(
                f"| {model_key} + {clf_key} | {o_f1:.4f} | {g_f1:.4f} | "
                f"{delta:+.4f} | {pct:+.1f}% |"
            )
            if g_f1 > best_grouped_f1:
                best_grouped_f1 = g_f1

    lines.append("")

    # Per-class breakdown for best model
    lines.append("## Per-Class F1 (Best Model: scibert + logreg)")
    lines.append("")
    lines.append("| Class | SH1 (random) | SH1b (grouped) | Delta |")
    lines.append("|---|---|---|---|")
    g_pc = grouped_results.get("scibert", {}).get("logreg", {}).get("test", {}).get("per_class_f1", {})
    o_pc = original_results.get("scibert", {}).get("logreg", {}).get("test", {}).get("per_class_f1", {})
    for cls in LABEL_NAMES:
        g_v = g_pc.get(cls, 0)
        o_v = o_pc.get(cls, 0)
        lines.append(f"| {cls} | {o_v:.4f} | {g_v:.4f} | {o_v - g_v:+.4f} |")
    lines.append("")

    # GroupKFold CV
    lines.append("## GroupKFold Cross-Validation (5-fold)")
    lines.append("")
    lines.append("| Model + Clf | Mean F1 ± Std | Folds |")
    lines.append("|---|---|---|")
    for key, cv in cv_results.items():
        folds_str = ", ".join(f"{f:.4f}" for f in cv["fold_f1s"])
        lines.append(f"| {key} | {cv['mean_f1']:.4f} ± {cv['std_f1']:.4f} | [{folds_str}] |")
    lines.append("")

    # Verdict
    best_orig = original_results.get("best_config", {}).get("test_f1", 0.72)
    delta = best_orig - best_grouped_f1

    lines.append("## Verdict")
    lines.append("")
    lines.append(f"- **SH1 (random split)**: F1 = {best_orig:.4f}")
    lines.append(f"- **SH1b (grouped split)**: F1 = {best_grouped_f1:.4f}")
    lines.append(f"- **Delta (inflation)**: {delta:+.4f}")
    lines.append("")

    if delta < 0.05:
        verdict = "NEGLIGIBLE — leakage < 0.05. SH1 result stands. Grouped F1 should be reported as primary metric for rigor."
    elif delta < 0.10:
        verdict = "MODERATE — inflation 0.05–0.10. Report grouped F1 as primary result. SH1 conclusion (SLoD is decodable) still holds if grouped F1 > 0.60."
    else:
        verdict = "SIGNIFICANT — inflation > 0.10. SH1 result must be revised. Report grouped F1 as the true performance."

    lines.append(f"**{verdict}**")
    lines.append("")

    if best_grouped_f1 >= 0.60:
        lines.append("**SH1 CONFIRMED** (with grouped split): SLoD remains linearly decodable above threshold (0.60).")
    elif best_grouped_f1 >= 0.50:
        lines.append("**SH1 PARTIAL** (with grouped split): SLoD signal present but weaker than originally reported.")
    else:
        lines.append("**SH1 NOT CONFIRMED** (with grouped split): SLoD signal does not survive document-level evaluation.")

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines))
    logging.info(f"Report saved to {report_path}")


def main():
    setup_logging()
    logger = logging.getLogger(__name__)

    config = load_config(PROJECT_ROOT / "config.yaml")
    data_dir = PROJECT_ROOT / config["data_dir"]
    sh0_dir = PROJECT_ROOT / config["sh0_data_dir"]
    reports_dir = PROJECT_ROOT / config["reports_dir"]
    embeddings_dir = data_dir / "embeddings"
    results_dir = data_dir / "results"
    results_dir.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------
    # Step 1: Load spans and create grouped splits
    # ---------------------------------------------------------------
    print("\n" + "=" * 60)
    print("SH1b: DOCUMENT-LEVEL SPLIT VALIDATION")
    print("=" * 60)

    spans = load_spans(sh0_dir / config["primary_dataset"])
    paper_ids = np.array([s["paper_id"] for s in spans])
    labels = np.array([LABEL_MAP[s["label"]] for s in spans])

    splits_path = data_dir / "splits_grouped.json"
    if splits_path.exists():
        logger.info("Grouped splits already exist, loading.")
        with open(splits_path) as f:
            splits = json.load(f)
    else:
        logger.info("Creating grouped splits (by paper_id)...")
        splits = create_grouped_splits(
            spans,
            ratios=config["split_ratios"],
            seed=config["random_seed"],
            save_path=splits_path,
        )

    train_idx = np.array(splits["train"])
    val_idx = np.array(splits["val"])
    test_idx = np.array(splits["test"])

    # Collect split statistics
    split_stats = {}
    for name, idx in [("train", train_idx), ("val", val_idx), ("test", test_idx)]:
        split_stats[name] = {
            "n_papers": len(set(paper_ids[idx])),
            "n_spans": len(idx),
            "label_dist": label_distribution(labels[idx]),
        }
        print(
            f"  {name}: {split_stats[name]['n_papers']} papers, "
            f"{split_stats[name]['n_spans']} spans  {split_stats[name]['label_dist']}"
        )

    # Verify zero overlap
    assert len(set(paper_ids[train_idx]) & set(paper_ids[test_idx])) == 0
    assert len(set(paper_ids[train_idx]) & set(paper_ids[val_idx])) == 0
    assert len(set(paper_ids[val_idx]) & set(paper_ids[test_idx])) == 0
    print("  Zero paper overlap: ✓")

    # ---------------------------------------------------------------
    # Step 2: Train probes with grouped splits
    # ---------------------------------------------------------------
    print("\n" + "=" * 60)
    print("STEP 2: Training probes with grouped splits")
    print("=" * 60)

    all_results = {}

    for model_key in config["models"]:
        npz_path = embeddings_dir / f"{model_key}_length_matched.npz"
        if not npz_path.exists():
            logger.warning(f"Embeddings not found for {model_key}, skipping.")
            continue

        print(f"\n--- {model_key} ---")
        data = np.load(npz_path, allow_pickle=True)
        embeddings = data["embeddings"]
        emb_labels = data["labels"]

        X_train = embeddings[train_idx]
        y_train = emb_labels[train_idx]
        X_val = embeddings[val_idx]
        y_val = emb_labels[val_idx]
        X_test = embeddings[test_idx]
        y_test = emb_labels[test_idx]

        model_results = {}
        for clf_key, clf_config in config["classifiers"].items():
            print(f"  {clf_key}: ", end="", flush=True)

            C_values = clf_config.get("C_search", [1.0])
            best_c, best_val_f1 = run_hyperparameter_sweep(
                X_train, y_train, X_val, y_val, C_values, clf_config
            )

            metrics = train_and_evaluate(
                X_train, y_train, X_val, y_val, X_test, y_test, clf_config, C=best_c
            )

            test_f1 = metrics["test"]["macro_f1"]
            print(f"test F1={test_f1:.4f} (C={best_c})")
            model_results[clf_key] = metrics

        all_results[model_key] = model_results

    # ---------------------------------------------------------------
    # Step 3: GroupKFold cross-validation
    # ---------------------------------------------------------------
    print("\n" + "=" * 60)
    print("STEP 3: GroupKFold cross-validation (5-fold)")
    print("=" * 60)

    cv_results = {}
    for model_key in config["models"]:
        npz_path = embeddings_dir / f"{model_key}_length_matched.npz"
        if not npz_path.exists():
            continue

        data = np.load(npz_path, allow_pickle=True)
        embeddings = data["embeddings"]
        emb_labels = data["labels"]

        for clf_key, clf_config in config["classifiers"].items():
            # Use the best C from the grouped split run
            best_c = all_results.get(model_key, {}).get(clf_key, {}).get("C", 1.0)
            key = f"{model_key} + {clf_key}"
            print(f"\n  {key} (C={best_c}):")

            cv = run_groupkfold_cv(
                embeddings, emb_labels, paper_ids, clf_config, C=best_c, n_folds=5
            )
            cv_results[key] = cv
            print(f"  → Mean F1 = {cv['mean_f1']:.4f} ± {cv['std_f1']:.4f}")

    # ---------------------------------------------------------------
    # Step 4: Load original results and compare
    # ---------------------------------------------------------------
    print("\n" + "=" * 60)
    print("STEP 4: Comparison with original SH1")
    print("=" * 60)

    orig_results_path = results_dir / "probe_results.json"
    if orig_results_path.exists():
        with open(orig_results_path) as f:
            original_results = json.load(f)
    else:
        logger.warning("Original probe_results.json not found, comparison will be empty.")
        original_results = {}

    # Print comparison table
    print(f"\n{'Model + Clf':<25} {'SH1 (random)':>14} {'SH1b (grouped)':>16} {'Delta':>8}")
    print("-" * 65)
    for model_key in all_results:
        for clf_key in all_results[model_key]:
            g_f1 = all_results[model_key][clf_key]["test"]["macro_f1"]
            o_f1 = original_results.get(model_key, {}).get(clf_key, {}).get("test", {}).get("macro_f1", 0)
            delta = o_f1 - g_f1
            print(f"  {model_key} + {clf_key:<12} {o_f1:>12.4f} {g_f1:>14.4f} {delta:>+8.4f}")

    # ---------------------------------------------------------------
    # Step 5: Save results and generate report
    # ---------------------------------------------------------------
    output = {
        "grouped_probe_results": all_results,
        "cv_results": cv_results,
        "split_stats": split_stats,
    }
    output_path = results_dir / "probe_results_grouped.json"
    with open(output_path, "w") as f:
        json.dump(output, f, indent=2)
    print(f"\nResults saved to {output_path}")

    report_path = reports_dir / "SH1b_GROUPED_SPLIT_REPORT.md"
    generate_report(all_results, original_results, split_stats, cv_results, report_path)
    print(f"Report saved to {report_path}")

    print("\nDone.\n")


if __name__ == "__main__":
    main()
